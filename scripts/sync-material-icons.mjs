async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return response.text();
}

const commit = JSON.parse(
  await download('https://api.github.com/repos/google/material-design-icons/commits/master'),
).sha;
const upstream = `https://raw.githubusercontent.com/google/material-design-icons/${commit}`;
const directory = new URL('../src/components/icons/', import.meta.url);
await mkdir(directory, { recursive: true });
const sources = new Map();
// Fetch small batches to avoid excessive connections to the upstream repository.
const symbols = [...new Set(Object.values(icons))];
for (let index = 0; index < symbols.length; index += 8) {
  await Promise.all(
    symbols.slice(index, index + 8).map(async (symbol) => {
      const svg = await download(
        `https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/${symbol}/wght500/24px.svg`,
      );
      const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
      const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"[^>]*\/?\s*>/g)].map(
        (match) => match[1],
      );
      if (!viewBox || !paths.length || /<(?:circle|rect|polygon|g)\b/.test(svg)) {
        throw new Error(`Unsupported SVG structure: ${symbol}`);
      }
      sources.set(symbol, { viewBox, paths });
    }),
  );
}

const exports = Object.entries(icons).map(([name, symbol]) => {
  const { viewBox, paths } = sources.get(symbol);
  return `export const ${name} = /*#__PURE__*/ createMaterialIcon(${JSON.stringify(symbol)}, ${JSON.stringify(viewBox)}, ${JSON.stringify(paths)});`;
});
await writeFile(
  new URL('index.ts', directory),
  `// Generated by scripts/sync-material-icons.mjs. See NOTICE.md for source and license.
import { defineComponent, h } from 'vue';

function createMaterialIcon(name: string, viewBox: string, paths: string[]) {
  return defineComponent({
    name: 'Material' + name,
    setup() {
      return () => h('svg', {
        xmlns: 'http://www.w3.org/2000/svg',
        viewBox,
        width: '1em',
        height: '1em',
        fill: 'currentColor',
        'aria-hidden': 'true',
        focusable: 'false',
        'data-material-icon': name,
      }, paths.map((d) => h('path', { d })));
    },
  });
}

${exports.join('\n')}
`,
);
await writeFile(new URL('LICENSE', directory), await download(`${upstream}/LICENSE`));
