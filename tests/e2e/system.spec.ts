import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function login(page: Page, username: string, destination: string, password = 'Demo@123456') {
  await page.goto(destination)
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(destination)
}
const rowWith = (page: Page, text: string) => page.locator('.el-table__body-wrapper tbody tr').filter({ hasText: text })

test('admin creates a role and user; changes revoke permissions and disabling revokes an existing session', async ({ page, browser, baseURL }) => {
  const code = 'e2e_operator'
  const name = '设备维护测试员'
  await login(page, 'admin', '/system/roles')
  await page.getByRole('button', { name: '新增角色', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeInViewport()
  await dialog.getByRole('textbox', { name: '角色名称', exact: true }).fill(name)
  await dialog.getByRole('textbox', { name: '角色编码', exact: true }).fill(code)
  await dialog.getByText('编辑设备', { exact: true }).click()
  await dialog.getByText('管理角色及权限', { exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '查看设备', exact: true })).toBeChecked()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(rowWith(page, name)).toBeVisible()

  await page.goto('/system/users')
  await page.getByRole('button', { name: '新增用户', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '用户名', exact: true }).fill(code)
  await dialog.getByRole('textbox', { name: '显示名称', exact: true }).fill('测试操作员')
  await dialog.getByLabel('初始密码', { exact: true }).fill('Password12345')
  await dialog.locator('.el-select__wrapper').click()
  await page.getByRole('option', { name, exact: true }).click()
  await dialog.getByRole('textbox', { name: '显示名称', exact: true }).click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(rowWith(page, code)).toBeVisible()

  const memberContext = await browser.newContext({ baseURL })
  try {
    const member = await memberContext.newPage()
    await login(member, code, '/device', 'Password12345')
    await expect(member.getByRole('button', { name: '编辑', exact: true })).toHaveCount(10)
    await expect(member.locator('.app-menu').getByRole('menuitem', { name: '用户管理' })).toHaveCount(0)
    await page.goto('/system/roles')
    await rowWith(page, name).getByRole('button', { name: '编辑', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByText('编辑设备', { exact: true }).click()
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(dialog).toBeHidden()
    await member.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(member.getByRole('button', { name: '编辑', exact: true })).toHaveCount(0)
    // 修改自己所属角色后，失去当前页面权限应跳到 403，不能留下空白内容区。
    await member.goto('/system/roles')
    await rowWith(member, name).getByRole('button', { name: '编辑', exact: true }).click()
    const ownDialog = member.getByRole('dialog')
    await ownDialog.getByText('查看角色', { exact: true }).click()
    await expect(ownDialog.getByRole('checkbox', { name: '管理角色及权限', exact: true })).not.toBeChecked()
    await ownDialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(member).toHaveURL('/403')
    await page.goto('/system/users')
    await rowWith(page, code).getByRole('button', { name: '编辑', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('switch', { name: '启用账号', exact: true }).locator('..').click()
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(dialog).toBeHidden()
    await member.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(member).toHaveURL(/\/login/)
  } finally { await memberContext.close() }

  await rowWith(page, code).getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '删除用户' }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(rowWith(page, code)).toHaveCount(0)
  await page.goto('/system/roles')
  await rowWith(page, name).getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '删除角色' }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(rowWith(page, name)).toHaveCount(0)
})

test('menu edits update navigation, preserve direct access, and the editor works in dark mobile layout', async ({ page }) => {
  await login(page, 'admin', '/system/menus')
  await rowWith(page, '/device').getByRole('button', { name: '编辑', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '菜单名称', exact: true }).fill('设备总览')
  await dialog.getByRole('switch', { name: '显示菜单', exact: true }).locator('..').click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('.app-menu').getByRole('menuitem', { name: '设备列表', exact: true })).toHaveCount(0)
  await page.goto('/device')
  await expect(page.getByRole('heading', { name: '设备总览', exact: true })).toBeVisible()
  await expect(page.locator('.el-table__body-wrapper tbody tr')).toHaveCount(10)
  await page.goto('/system/menus')
  await page.getByRole('button', { name: '切换主题', exact: true }).click()
  await page.getByRole('menuitem', { name: '深色模式', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.setViewportSize({ width: 390, height: 844 })
  await rowWith(page, '/device').getByRole('button', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await dialog.getByRole('textbox', { name: '菜单名称', exact: true }).fill('设备列表')
  await dialog.getByRole('switch', { name: '显示菜单', exact: true }).locator('..').click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: '展开侧栏', exact: true }).first().click()
  await expect(page.locator('.app-menu').getByRole('menuitem', { name: '设备列表', exact: true })).toBeVisible()
})
