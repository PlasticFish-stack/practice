import { test, expect } from '@playwright/test'

test('menu tree collapses and sibling drag order persists', async ({ page }) => {
  await page.goto('/system/menus')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('Demo@123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  const rows = page.locator('.el-table__body-wrapper tbody tr')
  const child = rows.filter({ hasText: 'WebSocket 演示' })
  await expect(child).toBeVisible()
  await page.getByRole('button', { name: '全部折叠', exact: true }).click()
  await expect(child).toBeHidden()
  await page.getByRole('button', { name: '全部展开', exact: true }).click()
  await expect(child).toBeVisible()
  const headers = page.locator('.el-table__header-wrapper th')
  await expect(headers.nth(0).locator('.el-checkbox')).toBeVisible()
  await expect(headers.nth(2)).toHaveText('菜单名称')
  await expect(rows.first().locator('td').nth(2).getByRole('button', { name: '拖拽调整同级顺序' })).toBeVisible()
  const parent = rows.filter({ has: page.locator('.menu-title', { hasText: '开发演示' }) })
  await expect(parent.locator('td').nth(1).locator('.el-table__expand-icon')).toBeVisible()
  await expect(parent.locator('td').nth(2).locator('.el-table__expand-icon')).toHaveCount(0)
  await parent.locator('.el-table__expand-icon').click()
  await expect(child).toBeHidden()
  await parent.locator('.el-table__expand-icon').click()
  await expect(child).toBeVisible()
  const source = rows.filter({ hasText: '个人中心' }).getByRole('button', { name: '拖拽调整同级顺序' })
  const target = rows.filter({ has: page.locator('.menu-title', { hasText: '角色管理' }) }).locator('.row-drop-zone')
  await source.dragTo(target)
  await expect(page.getByText('菜单顺序已保存', { exact: true })).toBeVisible()
  await page.reload()
  await expect(rows.first()).toBeVisible()
  const titles = await rows.allTextContents()
  expect(titles.findIndex(text => text.includes('个人中心'))).toBeLessThan(titles.findIndex(text => text.includes('角色管理')))
})

test('dark table keeps fixed actions consistent and scrollbar outside selected cells', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 900 })
  await page.addInitScript(() => localStorage.setItem('ui.theme', 'dark'))
  await page.goto('/system/menus')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('Demo@123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  const table = page.locator('.app-table')
  const header = table.locator('th.app-action-cell')
  const background = await header.evaluate(element => getComputedStyle(element).backgroundColor)
  expect(background).toBe(await table.locator('th').nth(3).evaluate(element => getComputedStyle(element).backgroundColor))
  const wrap = table.locator('.el-scrollbar__wrap')
  const dimensions = await wrap.evaluate(element => ({ width: element.clientWidth, scrollWidth: element.scrollWidth, gutter: element.offsetHeight - element.clientHeight }))
  expect(dimensions.scrollWidth).toBeGreaterThan(dimensions.width)
  await table.locator('.el-scrollbar').hover()
  await expect(table.locator('.el-scrollbar__bar.is-horizontal')).toBeVisible()
  const track = await table.locator('.el-scrollbar__bar.is-horizontal').boundingBox()
  const content = await table.locator('.el-scrollbar__wrap').boundingBox()
  expect(track!.y).toBeGreaterThanOrEqual(content!.y + content!.height)
  const lastRow = table.locator('tbody tr').last()
  await lastRow.locator('td').nth(6).click({ position: { x: 10, y: 15 } })
  await expect(lastRow.locator('td').nth(6)).toHaveClass(/is-cell-active/)
  await wrap.evaluate(element => { element.scrollLeft = element.scrollWidth })
  await expect(header).toBeVisible()
  await lastRow.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await wrap.evaluate(element => { element.scrollLeft = 0 })
  await lastRow.locator('td').nth(3).click()
  await table.locator('.el-scrollbar').hover()
  await page.screenshot({ path: 'artifacts/menu-dark-fixed.png', fullPage: true })
})



test('cell ranges support click, drag, keyboard and copy without changing row selection', async ({ page }) => {
  await page.goto('/system/menus')
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('Demo@123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  const table = page.locator('.app-table')
  const rows = table.locator('.el-table__body > tbody > tr.el-table__row')
  const name = rows.nth(0).locator('td').nth(2)
  const path = rows.nth(1).locator('td').nth(3)
  await name.locator('.menu-title').click()
  await expect(name).toHaveClass(/is-cell-active/)
  await expect(table.locator('td.is-cell-selected')).toHaveCount(1)
  await expect(rows.nth(0).getByRole('checkbox')).not.toBeChecked()
  await path.click({ modifiers: ['Shift'] })
  await expect(table.locator('td.is-cell-selected')).toHaveCount(4)
  const expectedCopy = await rows.evaluateAll(items => items.slice(0, 2).map(row => Array.from(row.querySelectorAll('td')).slice(2, 4).map(cell => cell.innerText.trim().replace(/\r?\n/g, ' ')).join('\t')).join('\n'))
  const copied = await table.evaluate(element => {
    const clipboardData = new DataTransfer()
    element.dispatchEvent(new ClipboardEvent('copy', { bubbles: true, cancelable: true, clipboardData }))
    return clipboardData.getData('text/plain')
  })
  expect(copied).toBe(expectedCopy)
  await page.keyboard.press('Escape')
  await expect(table.locator('td.is-cell-selected')).toHaveCount(0)
  const from = await name.boundingBox(), to = await path.boundingBox()
  await page.mouse.move(from!.x + from!.width - 6, from!.y + 8)
  await page.mouse.down()
  await page.mouse.move(to!.x + to!.width / 2, to!.y + to!.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(table.locator('td.is-cell-selected')).toHaveCount(4)
  await page.keyboard.press('ArrowRight')
  await expect(rows.nth(1).locator('td').nth(4)).toHaveClass(/is-cell-active/)
  await expect(table.locator('td.is-cell-selected')).toHaveCount(1)
  await page.getByRole('button', { name: '全部折叠', exact: true }).click()
  await expect(table.locator('td.is-cell-selected')).toHaveCount(0)
  await rows.nth(0).locator('td').nth(2).click()
  await page.screenshot({ path: 'artifacts/menu-cell-selection.png', fullPage: true })
  await page.getByRole('textbox', { name: '搜索菜单' }).click()
  await expect(table.locator('td.is-cell-selected')).toHaveCount(0)
})
